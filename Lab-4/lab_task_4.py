import pandas as pd
import matplotlib.pyplot as plt
#Load the Titanic dataset
df=pd.read_csv("train.csv")
print(" First 5 rows")
print(df.head())

print( "Numerical & Categorical Attribute")
print(df.columns.tolist())

"""Problem 2 – Line Plot"""

average = df.groupby("Pclass")["Fare"].mean()

plt.plot(average.index, average.values)

plt.title("Average Fare by Passenger Class")
plt.xlabel("Passenger Class")
plt.ylabel("Average Fare")

plt.show()

"""Problem 3 – Scatter Plot"""

plt.scatter(df["Age"], df["Fare"])

plt.title("Age and Fare")
plt.xlabel("Age")
plt.ylabel("Fare")

plt.show()

"""Problem 4 – Bar Chart"""

# Count male and female passengers
gender = df["Sex"].value_counts()

# Create bar chart
plt.bar(gender.index, gender.values)

plt.title("Male and Female Passengers")
plt.xlabel("Gender")
plt.ylabel("Number of Passengers")

plt.show()

"""Problem 5 – Histogram"""

# Show the distribution of passenger ages
plt.hist(df["Age"], bins=20,  edgecolor="black")

plt.title("Passenger Age Distribution")
plt.xlabel("Age")
plt.ylabel("Number of Passengers")

plt.show()

"""Problem 6 – Pie Chart"""

# Count survived and not survived passengers
survival = df["Survived"].value_counts()

# Create pie chart
plt.pie(survival, labels=["Not Survived", "Survived"],
        autopct="%.1f%%")

plt.title("Passenger Survival")

plt.show()

"""Problem 7 – Two Subplots"""

# Create two plots
fig, ax = plt.subplots(1, 2)

# First plot: Age histogram
ax[0].hist(df["Age"], bins=20, edgecolor="black")
ax[0].set_title("Passenger Age Distribution")
ax[0].set_xlabel("Age")
ax[0].set_ylabel("Frequency")

# Second plot: Passenger class
class_count = df["Pclass"].value_counts()

ax[1].bar(class_count.index, class_count.values)
ax[1].set_title("Passengers by Class")
ax[1].set_xlabel("Class")
ax[1].set_ylabel("Number of Passengers")

plt.show()

"""Problem 8 – Three Subplots"""

fig, ax = plt.subplots(1, 3, figsize=(10, 5))

# Bar Chart - Gender
gender_count = df["Sex"].value_counts()

ax[0].bar(gender_count.index, gender_count.values)
ax[0].set_title("Passengers by Gender")
ax[0].set_xlabel("Gender")
ax[0].set_ylabel("Number of Passengers")

# Histogram - Fare
ax[1].hist(df["Fare"], bins=10, edgecolor="black")
ax[1].set_title("Distribution of Passenger Fares")
ax[1].set_xlabel("Fare")
ax[1].set_ylabel("Frequency")

# Pie Chart - Survival
survival_count = df["Survived"].value_counts()

ax[2].pie(
    survival_count,
    labels=["Not Survived", "Survived"],
    autopct="%.1f%%"
)
ax[2].set_title("Survival Proportion")

plt.show()